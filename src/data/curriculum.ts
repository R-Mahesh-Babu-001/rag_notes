export function getStepBySlug(slug: string): RagProcessStep | undefined {
  return RAG_STEPS.find((s) => s.slug === slug);
}

export function getStepsByPhase(): { phase: RagPhase; steps: RagProcessStep[] }[] {
  return PHASE_ORDER.map((phase) => ({
    phase,
    steps: RAG_STEPS.filter((s) => s.phase === phase),
  }));
}
